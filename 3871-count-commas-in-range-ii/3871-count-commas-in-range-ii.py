class Solution:
    def countCommas(self, n: int) -> int:
        count = 0

        while n > 999:

            # 1,000 to 999,999
            if n < 1000000:
                count += (n - 999) * 1
                break

            # 1,000,000 to 999,999,999
            elif n < 1000000000:
                count += (n - 999999) * 2
                n = 999999

            # 1,000,000,000 to 999,999,999,999
            elif n < 1000000000000:
                count += (n - 999999999) * 3
                n = 999999999

            # 1,000,000,000,000 to 999,999,999,999,999
            elif n < 1000000000000000:
                count += (n - 999999999999) * 4
                n = 999999999999

            # 1,000,000,000,000,000+
            else:
                count += (n - 999999999999999) * 5
                n = 999999999999999

        return count